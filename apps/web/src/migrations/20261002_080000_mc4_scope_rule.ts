import { type MigrateDownArgs, type MigrateUpArgs, sql } from '@payloadcms/db-postgres'

/**
 * PT scope rule (owner decision 2026-10-02, ADR 0016 "Scope rule"), run as <prefix>_owner:
 *
 * 1. QA-MC4-07 — `owner_company_id` on the five owner-linked media tables (`ownerCompany`, Payload
 *    relationship to `companies`, FK ON DELETE SET NULL, btree index). The value is DERIVED by the DB,
 *    never taken from the client: `pk_media_owner_company()` (BEFORE INSERT OR UPDATE) sets it from the
 *    owner link (`expense_request` → expense_requests, `progress_report` → progress_reports,
 *    `cash_entry` → cash_entries; owner link and the owner's `company_id` are both immutable), selfies
 *    from their earliest attendance; `pk_attendance_selfie_company()` (AFTER INSERT ON attendances)
 *    fills it when the attendance is written after the selfie upload. Office read rules become
 *    `owner_company_id IN (…)` instead of `id IN (<every owner document of the PTs>)` (bind-parameter
 *    cap 65 535 per statement).
 * 2. QA-MC4-06 — `receipt_flags.related_company_id`: PT of `related_request_id` when it is NOT the
 *    flag's own PT (cross-PT duplicate, shown only to users mapped to that PT); set by the app.
 *
 * Backfill: set-based, idempotent (only rows whose stored value differs from the derived one), so a
 * re-run changes nothing. `receipt_flags_guard` (identity immutable) is disabled for the backfill
 * statement only, inside this migration's transaction. Down: triggers, functions, then the columns.
 */
const MEDIA = ['media_receipts', 'media_transfer_proofs', 'media_selfies', 'media_progress_photos', 'media_attachments'] as const
/** [table, column without `_id`] — constant identifiers (Payload names: `<table>_<column>_idx`, `<table>_<column>_id_companies_id_fk`). */
const COLUMNS: ReadonlyArray<readonly [string, string]> = [['receipt_flags', 'related_company'], ...MEDIA.map((t) => [t, 'owner_company'] as const)]

export async function up({ db }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
    DO $pk$
    BEGIN
      IF current_user !~ '_owner$' THEN
        RAISE EXCEPTION 'migrations must run as the <prefix>_owner role (current_user=%)', current_user;
      END IF;
    END
    $pk$;`)

  // 1. Payload columns (as generated by `payload migrate:create`, schema snapshot in the .json), written
  //    re-runnable: IF NOT EXISTS / constraint looked up first
  for (const [table, column] of COLUMNS) {
    await db.execute(sql.raw(`ALTER TABLE "${table}" ADD COLUMN IF NOT EXISTS "${column}_id" integer;`))
    await db.execute(
      sql.raw(`DO $pk$ BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${table}_${column}_id_companies_id_fk') THEN
          ALTER TABLE "${table}" ADD CONSTRAINT "${table}_${column}_id_companies_id_fk" FOREIGN KEY ("${column}_id") REFERENCES "public"."companies"("id") ON DELETE set null ON UPDATE no action;
        END IF;
      END $pk$;`),
    )
    await db.execute(sql.raw(`CREATE INDEX IF NOT EXISTS "${table}_${column}_idx" ON "${table}" USING btree ("${column}_id");`))
  }

  // 2. derivation (the client never sets owner_company_id: any written value is replaced)
  await db.execute(sql`
    CREATE OR REPLACE FUNCTION pk_media_owner_company() RETURNS trigger LANGUAGE plpgsql AS $fn$
    BEGIN
      IF TG_TABLE_NAME = 'media_selfies' THEN
        NEW.owner_company_id := (SELECT a.company_id FROM attendances a WHERE a.selfie_id = NEW.id ORDER BY a.id LIMIT 1);
      ELSIF NEW.owner_doc_id IS NULL OR NEW.owner_doc_id !~ '^[0-9]{1,10}$' THEN
        NEW.owner_company_id := NULL;
      ELSIF NEW.owner_doc_type = 'expense_request' THEN
        NEW.owner_company_id := (SELECT e.company_id FROM expense_requests e WHERE e.id = NEW.owner_doc_id::bigint);
      ELSIF NEW.owner_doc_type = 'progress_report' THEN
        NEW.owner_company_id := (SELECT r.company_id FROM progress_reports r WHERE r.id = NEW.owner_doc_id::bigint);
      ELSIF NEW.owner_doc_type = 'cash_entry' THEN
        NEW.owner_company_id := (SELECT c.company_id FROM cash_entries c WHERE c.id = NEW.owner_doc_id::bigint);
      ELSE
        NEW.owner_company_id := NULL;
      END IF;
      RETURN NEW;
    END
    $fn$;

    CREATE OR REPLACE FUNCTION pk_attendance_selfie_company() RETURNS trigger LANGUAGE plpgsql AS $fn$
    BEGIN
      UPDATE media_selfies SET owner_company_id = NEW.company_id WHERE id = NEW.selfie_id AND owner_company_id IS NULL;
      RETURN NULL;
    END
    $fn$;

    DROP TRIGGER IF EXISTS attendances_selfie_company ON attendances;
    CREATE TRIGGER attendances_selfie_company AFTER INSERT ON attendances FOR EACH ROW EXECUTE FUNCTION pk_attendance_selfie_company();`)
  for (const t of MEDIA) {
    await db.execute(sql.raw(`DROP TRIGGER IF EXISTS ${t}_owner_company ON ${t};`))
    await db.execute(sql.raw(`CREATE TRIGGER ${t}_owner_company BEFORE INSERT OR UPDATE ON ${t} FOR EACH ROW EXECUTE FUNCTION pk_media_owner_company();`))
  }

  // 3. backfill (idempotent; the BEFORE UPDATE trigger derives the same value)
  for (const t of ['media_receipts', 'media_transfer_proofs', 'media_progress_photos', 'media_attachments'] as const) {
    await db.execute(
      sql.raw(`
      UPDATE ${t} m SET owner_company_id = d.company_id
        FROM (SELECT x.id, CASE x.owner_doc_type
                             WHEN 'expense_request' THEN (SELECT e.company_id FROM expense_requests e WHERE e.id = x.owner_doc_id::bigint)
                             WHEN 'progress_report' THEN (SELECT r.company_id FROM progress_reports r WHERE r.id = x.owner_doc_id::bigint)
                             WHEN 'cash_entry' THEN (SELECT c.company_id FROM cash_entries c WHERE c.id = x.owner_doc_id::bigint)
                           END AS company_id
                FROM ${t} x WHERE x.owner_doc_id ~ '^[0-9]{1,10}$') d
       WHERE d.id = m.id AND m.owner_company_id IS DISTINCT FROM d.company_id;`),
    )
  }
  await db.execute(sql`
    UPDATE media_selfies m SET owner_company_id = a.company_id
      FROM (SELECT DISTINCT ON (selfie_id) selfie_id, company_id FROM attendances ORDER BY selfie_id, id) a
     WHERE a.selfie_id = m.id AND m.owner_company_id IS DISTINCT FROM a.company_id;

    ALTER TABLE receipt_flags DISABLE TRIGGER receipt_flags_guard;
    UPDATE receipt_flags f SET related_company_id = e.company_id
      FROM expense_requests e
     WHERE e.id = f.related_request_id AND e.company_id <> f.company_id AND f.related_company_id IS DISTINCT FROM e.company_id;
    ALTER TABLE receipt_flags ENABLE TRIGGER receipt_flags_guard;`)
}

export async function down({ db }: MigrateDownArgs): Promise<void> {
  for (const t of MEDIA) await db.execute(sql.raw(`DROP TRIGGER IF EXISTS ${t}_owner_company ON ${t};`))
  await db.execute(sql`
    DROP TRIGGER IF EXISTS attendances_selfie_company ON attendances;
    DROP FUNCTION IF EXISTS pk_attendance_selfie_company();
    DROP FUNCTION IF EXISTS pk_media_owner_company();`)
  for (const [table, column] of COLUMNS) {
    await db.execute(sql.raw(`ALTER TABLE "${table}" DROP CONSTRAINT IF EXISTS "${table}_${column}_id_companies_id_fk";`))
    await db.execute(sql.raw(`DROP INDEX IF EXISTS "${table}_${column}_idx";`))
    await db.execute(sql.raw(`ALTER TABLE "${table}" DROP COLUMN IF EXISTS "${column}_id";`))
  }
}
