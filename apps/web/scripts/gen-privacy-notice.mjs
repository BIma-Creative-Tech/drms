// Bundles the employee privacy notice (Q-46, ASVS 8.3.3 / G-06) into the app at build time.
// Single source of the text: docs/proyekkas/legal/pemberitahuan-privasi.md (HR/legal owned; `docs/` is not in
// the Docker build context, so the app imports this generated TS module instead of reading the file).
// Output: src/legal/privacy-notice.generated.ts = markdown + version (from the "**Versi:** <n>" line) + title +
// safe HTML (src/legal/markdown.ts: escaped text, attribute-less tags only) + sha256 of the source.
// Usage: node scripts/gen-privacy-notice.mjs [--check]   (--check: exit 1 when the committed module is stale)
import { createHash } from 'node:crypto'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE_REL = 'docs/proyekkas/legal/pemberitahuan-privasi.md'
const source = path.resolve(root, '../..', SOURCE_REL)
const outTs = path.join(root, 'src/legal/privacy-notice.generated.ts')

const tmp = mkdtempSync(path.join(os.tmpdir(), 'pk-privacy-'))
try {
  const bundle = path.join(tmp, 'markdown.mjs')
  await build({
    entryPoints: [path.join(root, 'src/legal/markdown.ts')],
    outfile: bundle,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    logLevel: 'warning',
  })
  const { noticeMeta, parseMarkdown, renderHtml } = await import(pathToFileURL(bundle).href)
  const markdown = readFileSync(source, 'utf8').replace(/\r\n?/g, '\n')
  const { version, title } = noticeMeta(markdown)
  const html = renderHtml(parseMarkdown(markdown))
  const sha256 = createHash('sha256').update(markdown).digest('hex')
  const body = { source: SOURCE_REL, sha256, version, title, markdown, html }
  const ts =
    `/* GENERATED by scripts/gen-privacy-notice.mjs from ${SOURCE_REL} — do not edit; change the markdown and run\n` +
    `   \`npm run gen:privacy-notice\` (CI: check:privacy-notice). */\n` +
    `export const PRIVACY_NOTICE_SOURCE = ${JSON.stringify(body, null, 2)} as const\n`
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(outTs, 'utf8')
    } catch {
      current = ''
    }
    if (current !== ts) {
      console.error(`privacy notice drift: ${path.relative(process.cwd(), outTs)} is not up to date with ${SOURCE_REL} — run npm run gen:privacy-notice`)
      process.exit(1)
    }
    console.log(`privacy notice up to date (version ${version})`)
  } else {
    writeFileSync(outTs, ts)
    console.log(`wrote ${path.relative(process.cwd(), outTs)} (version ${version})`)
  }
} finally {
  rmSync(tmp, { recursive: true, force: true })
}
